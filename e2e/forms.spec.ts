import { expect, test } from "@playwright/test";

test("kontrol formulir meja dapat dipakai dengan keyboard", async ({
  page,
}, info) => {
  await page.goto("/");
  await page.getByRole("button", { name: "Masuk dengan kode" }).click();
  const name = page.getByLabel("Nama pemain");
  const invite = page.getByLabel("Kode undangan");
  await name.fill("Rani");
  await name.press("Tab");
  await expect(invite).toBeFocused();
  await invite.fill("abc123");
  await expect(invite).toHaveValue("ABC123");
  await page.screenshot({ path: info.outputPath("gabung.png") });
  await page.getByRole("button", { name: "Menu awal" }).click();
  await page.getByRole("button", { name: "Buat meja privat" }).click();
  await expect(page.getByLabel(/One-Time Guess/)).toHaveCount(0);
  await name.press("Enter");
  await page.getByRole("button", { name: "Tambahkan aturan lainnya" }).click();
  const modal = page.getByRole("dialog", { name: "Pilih aturan lainnya" });
  await expect(modal).toBeVisible();
  await modal.getByRole("button", { name: "Detail" }).first().click();
  await expect(modal.locator(".rule-detail-box")).toBeVisible();
  const rule = modal.getByLabel(/One-Time Guess/);
  await rule.focus();
  await rule.press("Space");
  await expect(rule).toBeChecked();
  const taxRule = modal.getByLabel(/Duke Blocks Tax/);
  await taxRule.click();
  await expect(taxRule).toBeChecked();
  await modal.getByRole("button", { name: "Simpan aturan" }).click();
  await expect(modal).toBeHidden();
  await expect(page.locator(".active-rule-chip")).toHaveCount(2);
  await page.getByRole("button", { name: "Ganti nama" }).click();
  await page.getByLabel("Nama baru").fill("Rani Baru");
  await page.screenshot({ path: info.outputPath("rename-inline.png") });
  await page.getByRole("button", { name: "Simpan", exact: true }).click();
  await expect(page.locator(".seat b").first()).toHaveText("Rani Baru");
  await page.getByRole("button", { name: "Tambah computer" }).click();
  const botName = (await page.locator(".seat").nth(1).locator("b").innerText()).trim();
  expect(botName).not.toMatch(/^Computer \d+$/);
  await page.getByLabel("Level " + botName).selectOption("hard");
  await expect(page.getByLabel("Level " + botName)).toHaveValue("hard");
  await page.screenshot({ path: info.outputPath("lobi.png") });
  await page.getByRole("button", { name: "Mulai pertandingan" }).click();
  await page.getByRole("button", { name: "Lihat meja" }).click();
  await page.getByRole("button", { name: "Menu meja" }).click();
  await page.getByText("Pengaturan meja", { exact: true }).click();
  await expect(rule).toHaveCount(0);
  await page.getByText("Pengaturan meja", { exact: true }).click();
  await page.getByText("Kontrol host", { exact: true }).click();
  await page.getByText("Koreksi koin", { exact: true }).click();
  await page.getByLabel("Saldo akhir").fill("4");
  await page.getByLabel("Alasan").fill("Koreksi saldo awal");
  await page.getByRole("button", { name: "Simpan koreksi" }).click();
  await page.getByRole("button", { name: "Tutup", exact: true }).click();
  await expect(page.locator(".player-area .balance")).toContainText("4 koin");
});
